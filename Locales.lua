-- Sprache anwenden: Englisch als Grundlage, darüber die gewählte Sprache. Der Probe-Zusatz
-- hängt seine Texte über SM.ExtraLocales an. Eine andere Sprache als die des Spiels kann man
-- in den Einstellungen wählen (wirkt nach /reload vollständig).
SM.ExtraLocales = {}
function SM:ApplyLanguage(code)
    for k in pairs(L) do L[k] = nil end
    English()
    if LANG[code] then LANG[code]() end
    for _, fn in ipairs(SM.ExtraLocales) do fn(code) end
    SM.locale = code
end
SM.LANGUAGES = { "deDE", "enUS", "zhCN" }
SM:ApplyLanguage(GetLocale())
